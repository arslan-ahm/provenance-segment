"""Publish the demo to a Hugging Face Space (Gradio SDK on free ZeroGPU hardware) with the `hf` CLI.

Docker and CPU Gradio Spaces need a paid plan; free accounts can host up to 2 ZeroGPU Gradio
Spaces. The Space gets exactly the committed files the app needs (src/, runs/), with
space/app.py as app.py, space/README.md as the Space card and space/requirements.txt, which
is generated from uv.lock (torch pinned to a ZeroGPU-supported release). Files that no longer
belong are removed in the same commit. Needs `hf auth login` locally, or HF_TOKEN in CI.

    uv run python scripts/deploy_space.py --write-requirements      # regenerate space/requirements.txt
    uv run python scripts/deploy_space.py --check-requirements      # CI: fail if it is stale
    uv run python scripts/deploy_space.py --space ARslan-Ahamd/provenance-segment --dry-run
    uv run python scripts/deploy_space.py --space ARslan-Ahamd/provenance-segment
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INCLUDE = ("LICENSE", "src/", "runs/")
SPACE_FILES = {"app.py": "space/app.py", "README.md": "space/README.md", "requirements.txt": "space/requirements.txt"}
REQUIREMENTS = ROOT / "space" / "requirements.txt"
ZEROGPU_TORCH = "torch==2.13.0"  # newest release in the ZeroGPU supported list (huggingface.co/docs/hub/spaces-zerogpu)


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True, capture_output=True, text=True).stdout


def staged_files() -> list[str]:
    files = [f for f in git("ls-files", "-z").split("\0") if f]
    return sorted(f for f in files if f in INCLUDE or any(p.endswith("/") and f.startswith(p) for p in INCLUDE))


def requirements_text() -> str:
    out = subprocess.run(
        ["uv", "export", "--frozen", "--no-hashes", "--no-dev", "--no-emit-project", "--no-header", "--no-annotate", "--extra", "nli", "--extra", "demo"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    lines, torch_done = [], False
    for line in out.splitlines():
        if not line.strip() or line.startswith("-"):
            continue
        if line.split("==")[0].strip() == "torch":
            if not torch_done:
                lines.append(ZEROGPU_TORCH)
                torch_done = True
            continue
        lines.append(line)
    header = "# Generated by scripts/deploy_space.py from uv.lock (extras nli + demo); torch pinned for ZeroGPU. Do not edit.\n"
    return header + "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--space", help="owner/name of the Space")
    ap.add_argument("--dry-run", action="store_true", help="list what would be uploaded and stop")
    ap.add_argument("--allow-dirty", action="store_true", help="deploy even if tracked files have uncommitted changes")
    ap.add_argument("--write-requirements", action="store_true", help="regenerate space/requirements.txt from uv.lock")
    ap.add_argument("--check-requirements", action="store_true", help="exit 1 if space/requirements.txt differs from uv.lock")
    args = ap.parse_args()

    if args.write_requirements:
        REQUIREMENTS.write_text(requirements_text(), encoding="utf-8", newline="\n")
        print(f"wrote {REQUIREMENTS.relative_to(ROOT)}")
        return 0
    if args.check_requirements:
        if REQUIREMENTS.read_text(encoding="utf-8") != requirements_text():
            print("space/requirements.txt is stale: run scripts/deploy_space.py --write-requirements", file=sys.stderr)
            return 1
        print("space/requirements.txt matches uv.lock")
        return 0
    if not args.space:
        ap.error("--space is required to deploy")

    if REQUIREMENTS.read_text(encoding="utf-8") != requirements_text():
        print("space/requirements.txt is stale: run --write-requirements and commit", file=sys.stderr)
        return 1
    dirty = git("status", "--porcelain", "--untracked-files=no", "--", *INCLUDE, "space/").strip()
    if dirty and not args.allow_dirty:
        print(f"Uncommitted changes in deployed paths; commit first or pass --allow-dirty:\n{dirty}", file=sys.stderr)
        return 1
    files = staged_files()
    commit = git("rev-parse", "--short", "HEAD").strip()
    size = sum((ROOT / f).stat().st_size for f in files)
    print(f"{len(files) + len(SPACE_FILES)} files, {size / 1e6:.1f} MB, from commit {commit} -> spaces/{args.space}")
    if args.dry_run:
        print("\n".join([*(f"{dst}  (from {src})" for dst, src in SPACE_FILES.items()), *files]))
        return 0
    if shutil.which("hf") is None:
        print("The `hf` CLI is not on PATH (uv tool install huggingface_hub).", file=sys.stderr)
        return 1

    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp)
        (out / "stage").mkdir()
        for f in files:
            (out / "stage" / f).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(ROOT / f, out / "stage" / f)
        for dst, src in SPACE_FILES.items():
            shutil.copy2(ROOT / src, out / "stage" / dst)
        # Free accounts: ZeroGPU Gradio Spaces only. Created private; making it public is the owner's call.
        subprocess.run(["hf", "repos", "create", args.space, "--type", "space", "--sdk", "gradio", "--flavor", "zero-a10g", "--private", "--exist-ok"], check=True)
        # On Windows the CLI expands wildcard arguments against the working directory, so run it
        # from an empty one: "*" then reaches the Hub as a pattern (remove files no longer deployed).
        empty = Path(tmp) / ".cwd"
        empty.mkdir()
        subprocess.run(
            ["hf", "upload", args.space, str(out / "stage"), ".", "--repo-type", "space", "--delete", "*", "--commit-message", f"Deploy {commit}"],
            check=True,
            cwd=empty,
        )
    print(f"https://huggingface.co/spaces/{args.space}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
